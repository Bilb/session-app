import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import type { ConfigContext, ExpoConfig } from 'expo/config'

/**
 * The locale list, read out of the generated catalogue rather than imported from it.
 *
 * Expo evaluates this file in plain node, and the workspace packages resolve to TypeScript source
 * that node cannot load -- `import { crowdinLocales } from '@session/localization'` fails before
 * the config is read at all. Copying eighty-one locale names into `app.json` instead would be a
 * second list to forget, which is the thing worth avoiding here. So the generated file is read as
 * text.
 *
 * It is generated by the shared translation scripts and its shape is fixed by them. If that ever
 * stops being true this throws rather than quietly declaring no localizations, because the failure
 * it would otherwise cause -- a settings page with no language row on it -- is invisible from here.
 */
function shippedLocales(): string[] {
  const generated = join(
    dirname(fileURLToPath(import.meta.url)),
    '../../packages/localization/src/localization-src/generated/constants.ts',
  )
  const listed = /crowdinLocales\s*=\s*\[([^\]]*)\]/s.exec(readFileSync(generated, 'utf8'))
  const locales = listed?.[1]?.match(/'([^']+)'/g)?.map((quoted) => quoted.slice(1, -1)) ?? []
  if (locales.length === 0) throw new Error(`no locales found in ${generated}`)
  return locales
}

/**
 * `app.json` plus the one thing that has to be computed.
 *
 * This file exists for `CFBundleLocalizations` and nothing else so far; everything static stays in
 * the JSON, where it is easier to read.
 */
/**
 * What a local build's bundle identifier gets on the end.
 *
 * **`-test` by default, and deliberately so.** An identifier is reserved with Apple by the first
 * account that builds it to a device, so a development build carrying the real one can take
 * `org.getsession.session2` against the wrong developer account -- quietly, and not easily undone.
 * The suffix keeps local builds out of that, and a release sets `SESSION_BUNDLE_SUFFIX=` (empty)
 * to ship the real identifier.
 *
 * This lived in the Xcode project until the project was regenerated, which lost it. Here it
 * survives a prebuild.
 */
const BUNDLE_SUFFIX = process.env['SESSION_BUNDLE_SUFFIX'] ?? '-test'

/** The identifier this build ships under: what `app.json` names, plus the suffix above. */
function bundleId(config: ConfigContext['config']): string {
  return `${config.ios?.bundleIdentifier ?? 'org.getsession.session2'}${BUNDLE_SUFFIX}`
}

/**
 * The camera permission's explanation, read out of the catalogue rather than written again here.
 *
 * iOS shows this string in its own prompt, so it is a user-visible string like any other and
 * belongs to Crowdin -- but a plist value is baked at build time, where `tr()` has no locale to
 * read. Same trick as the locale list above: the generated English is read as text. **Only English
 * for now**; localising a plist means the per-language `InfoPlist.strings` mechanism the legacy
 * client has, which is its own piece of work.
 */
function cameraPermissionText(): string {
  const generated = join(
    dirname(fileURLToPath(import.meta.url)),
    '../../packages/localization/src/localization-src/generated/english.ts',
  )
  const found = /cameraGrantAccessDescription:\s*'((?:[^'\\]|\\.)*)'/.exec(
    readFileSync(generated, 'utf8'),
  )
  if (!found?.[1]) throw new Error(`cameraGrantAccessDescription not found in ${generated}`)
  return found[1].replace(/\\'/g, "'")
}

export default ({ config }: ConfigContext): ExpoConfig => ({
  ...config,
  name: config.name ?? 'Session',
  slug: config.slug ?? 'session-app',
  // The camera is the scanner behind the restore screen's QR tab. Declared through the plugin
  // rather than by writing the plist key directly, so the Android permission comes with it.
  plugins: [
    ...(config.plugins ?? []),
    ['expo-camera', { cameraPermission: cameraPermissionText() }],
  ],
  ios: {
    ...config.ios,
    bundleIdentifier: bundleId(config),
    entitlements: {
      ...config.ios?.entitlements,
      // **Follows the identifier, because it has to.** The access group is the app's own identifier
      // prefixed by the team, so a `-test` build entitled to the unsuffixed group is entitled to a
      // group it is not in -- and the keychain refuses it. That surfaces as expo-secure-store
      // failing to store the database key, which is the app not starting rather than a warning.
      'keychain-access-groups': [`$(AppIdentifierPrefix)${bundleId(config)}`],
    },
    infoPlist: {
      ...config.ios?.infoPlist,
      /**
       * **What makes iOS offer a per-app language at all.**
       *
       * Settings shows a Preferred Language row only for a bundle that declares more than one
       * localization. Without this list the app's settings page has no language on it, so the
       * hand-off the language button offers would land somebody somewhere with nothing to change
       * -- which is why `openLanguageSettings` was null until now.
       *
       * The catalogue's own identifiers, which are Crowdin's. iOS matches these against the
       * device's preferred languages by the usual BCP-47 rules rather than exactly, so one it does
       * not recognise costs a row in that list and nothing else.
       */
      CFBundleLocalizations: shippedLocales(),
    },
  },
})
