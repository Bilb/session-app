import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * Turns libsession's URL table into TypeScript, so the app links the addresses it holds rather
 * than a second copy of them.
 *
 * The output is committed, so a checkout without the submodule still typechecks and
 * `codegen:check` is what stops it drifting. Why the addresses are generated rather than
 * delivered over the bridge or read natively: `docs/ARCHITECTURE.md`, *Where the addresses come
 * from*.
 */

const SUBMODULE = 'libsession-util'
const HEADER = join(SUBMODULE, 'include/session/session_protocol.h')
const TABLE = join(SUBMODULE, 'src/session_protocol.cpp')
const OUT = 'packages/app/src/urls.generated.ts'

const repoRoot = join(import.meta.dirname, '../../..')

function present(path: string): boolean {
  return existsSync(join(repoRoot, path))
}

function read(path: string): string {
  try {
    return readFileSync(join(repoRoot, path), 'utf8')
  } catch {
    throw new Error(
      `${path} is missing. The ${SUBMODULE} submodule is not checked out: ` +
        `\`git submodule update --init ${SUBMODULE}\` (no --recursive; its own externals are ` +
        `not needed to read this table).`,
    )
  }
}

/** The one block in each file worth reading, so a match elsewhere cannot be mistaken for it. */
function block(source: string, path: string, from: RegExp, to: string): string {
  const start = from.exec(source)
  if (start === null) throw new Error(`${path}: could not find the string table`)
  const rest = source.slice(start.index + start[0].length)
  const end = rest.indexOf(to)
  if (end === -1) throw new Error(`${path}: the string table has no end`)
  return rest.slice(0, end)
}

/**
 * Both files are read and required to agree, because a designated initializer has to be in
 * declaration order in C++ -- so the two disagreeing means the table upstream does not compile,
 * and parsing only one of them would emit a plausible file from a broken source.
 */
function fields(): { name: string; url: string }[] {
  const declared = [
    ...block(
      read(HEADER),
      HEADER,
      /typedef struct session_protocol_strings \{/,
      '} session_protocol_strings;',
    ).matchAll(/^\s*const char\* (\w+);$/gm),
  ].map((match) => match[1] as string)

  const initialised = [
    ...block(
      read(TABLE),
      TABLE,
      /const session_protocol_strings SESSION_PROTOCOL_STRINGS = \{/,
      '\n};',
    ).matchAll(/^\s*\.(\w+)\s*=\s*"([^"]*)"\w*,$/gm),
  ].map((match) => ({ name: match[1] as string, url: match[2] as string }))

  if (declared.join() !== initialised.map((field) => field.name).join())
    throw new Error(
      `${HEADER} and ${TABLE} disagree on the table:\n` +
        `  declared:    ${declared.join(', ')}\n` +
        `  initialised: ${initialised.map((field) => field.name).join(', ')}`,
    )

  // Only the addresses. The build-variant strings in the same struct name app stores, and belong
  // to whatever reports a build rather than to anything that opens a link.
  const urls = initialised.filter((field) => field.name.startsWith('url_'))
  if (urls.length === 0) throw new Error(`${TABLE}: the table carries no url_ fields`)

  const wrong = urls.filter((field) => !/^https:\/\/\S+$/.test(field.url))
  if (wrong.length > 0)
    throw new Error(
      `${TABLE}: not an https address: ${wrong.map((f) => `${f.name}=${f.url}`).join(', ')}`,
    )

  return urls
}

/** `url_pro_terms_of_service` becomes `proTermsOfService`. */
function key(name: string): string {
  return name
    .replace(/^url_/, '')
    .replace(/_(\w)/g, (_, character: string) => character.toUpperCase())
}

function emit(): string {
  const rows = fields()
    .map((field) => `  ${key(field.name)}: '${field.url}',`)
    .join('\n')

  return `// Generated by packages/app/scripts/generateUrls.ts from ${SUBMODULE}. Do not edit.
//
// Every address the app can send somebody to, keyed by the field it comes from.
//
// **Not translatable, which is why they are here rather than in the catalogue.** Most are
// reachable before anybody has decided to trust the app -- the terms and the privacy policy are
// on the landing screen itself -- and a URL a translation could change is a phishing surface.
// The catalogue supplies the words around a link and never the link.

export const URLS = {
${rows}
} as const
`
}

const target = join(repoRoot, OUT)

/**
 * Whether the library is here to read.
 *
 * **It is not, in CI.** The submodule is pinned at a commit the remote does not have, so no job
 * there can clone it -- and `codegen` runs there anyway, because every other task depends on it.
 *
 * So both modes fall back to the committed file rather than failing, and say which they did.
 * Saying so out loud rather than exiting quietly, because a step that silently proves nothing is
 * worse than one that is known not to have run.
 *
 * What still holds with no submodule: the generated file is committed, so it is reviewable and is
 * what every build actually compiles, and `urls.contract.test.ts` reads that file rather than the
 * library -- so a literal written out beside an address the table already carries is caught with
 * or without this.
 */
function readable(): boolean {
  return present(HEADER) && present(TABLE)
}

/** Nothing to read *and* nothing to fall back on is the one case that is a failure. */
function standDown(verb: string): never | void {
  if (!present(OUT))
    throw new Error(
      `neither ${SUBMODULE} nor ${OUT} is here, so there is nothing to ${verb} and nothing to ` +
        `fall back on. \`git submodule update --init ${SUBMODULE}\` (no --recursive; its own ` +
        `externals are not needed to read this table).`,
    )
  process.stdout.write(
    `${SUBMODULE} is not checked out, so ${OUT} was neither ${verb}d nor verified against it. ` +
      `Nothing is asserted here; run \`pnpm codegen\` in a tree that has it.\n`,
  )
}

if (process.argv.includes('--check')) {
  // Asked before the table is read, because reading it is the thing that cannot be done.
  if (!readable()) standDown('regenerate')
  else {
    if (readFileSync(target, 'utf8') !== emit()) {
      process.stderr.write(`${OUT} is stale. Run \`pnpm codegen\`.\n`)
      process.exit(1)
    }
    process.stdout.write(`${OUT} matches ${SUBMODULE}\n`)
  }
} else if (!readable()) standDown('regenerate')
else {
  writeFileSync(target, emit())
  process.stdout.write(`${OUT} written from ${SUBMODULE}\n`)
}
