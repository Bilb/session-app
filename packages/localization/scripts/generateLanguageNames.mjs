// Generates src/generated/languageNames.ts: each locale's name written in its own language.
//
// It exists because **Hermes has no `Intl.DisplayNames`**. Verified against the Hermes that ships
// with this React Native (0.17, build 250829098): its string table carries exactly three Intl
// constructors -- Collator, DateTimeFormat and NumberFormat. So the runtime that most needs this
// data is the one that cannot compute it.
//
// Node can, though, given a full-ICU build, which is what this uses. Right tool, wrong runtime:
// the fix is to run it at build time and ship the answer.
//
// The alternative is the `@formatjs/intl-displaynames` polyfill, which is the usual choice on React
// Native. It is the wrong shape here: it ships every language's name in every locale, plus region
// and script names, and a picker needs one cell of that matrix -- each language's name in its own
// language. Eighty strings against several megabytes.
//
// Run with `pnpm --filter @session/localization codegen`. CI runs `codegen:check`, which
// regenerates and fails on a diff, so a locale added upstream cannot arrive without its name.

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pkg = join(here, '..')

const constants = readFileSync(join(pkg, 'src/localization-src/generated/constants.ts'), 'utf8')
const block = constants.slice(constants.indexOf('export const crowdinLocales'))
// The region subtag can be numeric -- `es-419` is Latin American Spanish -- so this is not
// letters-only. A letters-only pattern silently dropped it, and the typecheck caught it as a
// missing key rather than it shipping as a blank row.
const locales = [
  ...new Set([...block.matchAll(/'([a-z]{2,3}(?:-[A-Za-z0-9]+)?)'/g)].map((m) => m[1])),
]

if (locales.length === 0) {
  throw new Error('No locales found in constants.ts — has the generated file moved?')
}

if (typeof Intl.DisplayNames !== 'function') {
  throw new Error('This node has no Intl.DisplayNames; a full-ICU build is required to generate.')
}

const names = {}
const unresolved = []
for (const locale of locales) {
  let name
  try {
    name = new Intl.DisplayNames([locale], { type: 'language' }).of(locale)
  } catch {
    name = undefined
  }
  // ICU echoes the code back when it has no name for it, which is not an answer.
  if (!name || name === locale) unresolved.push(locale)
  else names[locale] = name
}

if (unresolved.length > 0) {
  // Loud rather than silent: a locale with no name would render as a blank row in the picker, and
  // the fix (a hand-written entry) has to be a decision somebody makes.
  throw new Error(
    `No display name for: ${unresolved.join(', ')}. Add an override before regenerating.`,
  )
}

const entries = Object.entries(names)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, name]) => `  '${code}': ${JSON.stringify(name)},`)
  .join('\n')

const out = `// Generated by scripts/generateLanguageNames.mjs. Do not edit by hand.
//
// Each locale's name in its own language, because Hermes has no \`Intl.DisplayNames\` and a
// language picker has to render "Français" rather than "fr" on every platform. Regenerate with
// \`pnpm --filter @session/localization codegen\`.

import type { CrowdinLocale } from '../localization-src/generated/constants'

export const LANGUAGE_NAMES: Record<CrowdinLocale, string> = {
${entries}
}

/** The locale's own name for itself, falling back to the code so a picker row is never blank. */
export function languageName(locale: CrowdinLocale): string {
  return LANGUAGE_NAMES[locale] ?? locale
}
`

mkdirSync(join(pkg, 'src/generated'), { recursive: true })
writeFileSync(join(pkg, 'src/generated/languageNames.ts'), out)
// Formatted here rather than left for `format:check` to fail on, since generated output has to be
// committed in the shape the repo expects.
execFileSync('pnpm', ['exec', 'prettier', '--write', 'src/generated/languageNames.ts'], {
  cwd: pkg,
  stdio: 'ignore',
})

process.stdout.write(`generated ${entries.split('\n').length} language names\n`)
